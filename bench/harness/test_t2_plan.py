def in_memory_plans():
    """(plan 1, plan 2) for a made-up plan 1 that holds every key a real one does."""
    plan_1 = {"seed": "1", "beacon": {"round": 7}, "code": "a" * 40, "model": "m", "model_digest": "d", "model_quantization": "q",
              "server_version": "v", "server_config": {"x": "1"}, "size_vram": 1, "case_timeout": 1, "call_timeout": 1,
              "prose": {"eval/SCORING.md": "1" * 64, "docs/DESIGN.md": "2" * 64}, "labels": "l", "lists": {"a": "3" * 64}, "batches": [{"set": "T2-x"}]}
