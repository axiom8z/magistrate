def edited(block, old, new):
    """The block with one thing changed, which has to be there."""
    assert block.count(old) == 1, old
    return block.replace(old, new)


def edited_start(block, old, new):
    """The block with one thing changed in its start line, the one that holds the runner's command."""
    start, rest = block.split(b"\n", 1)
    return edited(start, old, new) + b"\n" + rest


class FakeServer:
    """Stands in for the model server and its log, so no test opens a socket. A chat loads the model, which appends the
    next of `blocks` to the log, if the model wasn't loaded; keep_alive 0 unloads it. A block None writes nothing, and
    `shows_loaded` False makes /api/ps say nothing is loaded."""
    BASE = "http://fake.invalid"
    DIGEST = "a" * 64

    def __init__(self, log, blocks=(BLOCK, BLOCK), version="0.40.14", size_vram=5016660212, shows_loaded=True):
        self.log, self.blocks, self.version, self.size_vram = pathlib.Path(log), list(blocks), version, size_vram
        self.shows_loaded = shows_loaded
        self.loaded, self.loads = False, 0

    def __call__(self, url, body=None, timeout=30):
        path = url.removeprefix(self.BASE)
        if path == "/api/tags":
            return {"models": [{"name": t2_plan.MODEL, "digest": self.DIGEST, "details": {"quantization_level": "Q4_K_M"}}]}
        if path == "/api/ps":
            return {"models": [{"name": t2_plan.MODEL, "digest": self.DIGEST, "size_vram": self.size_vram}] if self.loaded and self.shows_loaded else []}
        if path == "/api/version":
            return {"version": self.version}
        if path == "/api/show":
            return {"modelfile": f'# Modelfile generated by "ollama show"\nFROM C:\\fake\\models\\blobs\\sha256-{BLOB}\nTEMPLATE x\n'}
        if path == "/v1/chat/completions":
            if not self.loaded:
                self.loaded = True
                block = self.blocks[self.loads] if self.loads < len(self.blocks) else None
                self.loads += 1
                if block is not None:
                    with open(self.log, "ab") as log:
                        log.write(block)
            return {}
        if path == "/api/generate" and body.get("keep_alive") == 0:
            self.loaded = False
            return {}
        raise AssertionError(f"the fake server has no {path}")


def faked(server, action):
    """Runs `action` with t2_plan talking to `server`."""
    real = t2_plan.http_json
    t2_plan.http_json = server
    try:
        return action()
    finally:
        t2_plan.http_json = real


def problem_with(problems, text):
    return any(text in problem for problem in problems)


def check_parser():
    facts, offset, first, why = t2_plan.start_reading(DATA, BLOB)
    check(why is None and offset == START and first == DATA.split(b"\n")[0], "the shipped parser reads the fixture's load, and says where its block starts")
    check(facts["runner_flags"] == RUNNER_FLAGS, "the runner's flags, unescaped, from --model on, with paths and the port masked")
    check(facts["gpu_layers"] == "14/66" and facts["gpu_device"] == [GPU_DEVICE], "the split, and the compute line without `available`")
    config = facts["load_config"]
    check(len(config) == 185 and hashlib.sha256("\n".join(config).encode()).hexdigest() == LOAD_CONFIG_SHA256
          and config[0].startswith("common_param: common_params_print_info: build") and config[-1] == "warmup: flash attention is enabled"
          and "load_tensors: offloaded 14/66 layers to GPU" in config, "and 185 configuration lines, in order, with the `cmn` prefix dropped")
    check(not any(mark in line for line in config + [facts["runner_flags"]] for mark in ("fake", "\\\\", ":\\")), "no line names a path")
    crlf = DATA.replace(b"\n", b"\r\n")
    check(t2_plan.start_reading(crlf, BLOB)[0] == facts, "a log with CRLF line ends gives the same facts")
    # U+2028 is a line break to str.splitlines, and chat text at verbosity 4 can hold it.
    smuggled = edited(BLOCK, b"srv  server_setup:", "\u2028load_tensors: offloaded 9/9 layers to GPU srv  server_setup:".encode())
    check(t2_plan.start_reading(STARTUP + smuggled, BLOB)[0] == facts, "and text holding U+2028 doesn't split a line")


def check_guards():
    why = lambda data, blob=BLOB: t2_plan.start_reading(data, blob)[3] or ""
    check("missing or empty" in why(None) and "missing or empty" in why(b"") and "missing or empty" in why(b" \n"), "no log, an empty one and a blank one each refuse")
    check("blob isn't known" in why(DATA, None), "an unknown model blob refuses")
    check("belongs to this model" in why(STARTUP + edited_start(BLOCK, BLOB.encode(), b"0" * 64)), "a log with only another model's load refuses")
    check("0 offloaded" in why(STARTUP + edited(BLOCK, OFFLOADED_LINE, b"")), "a block with no offloaded line refuses")
    check("2 offloaded" in why(STARTUP + edited(BLOCK, OFFLOADED_LINE, OFFLOADED_LINE * 2)), "and one with two")
    check("no inference compute" in why(DATA.replace(b'msg="inference compute"', b'msg="inference"')), "a log with no compute line refuses")
    check(why(STARTUP + BLOCK + edited(BLOCK, OFFLOADED_LINE, b"")) != "", "only the model's last block is read, so a bad last block refuses though an earlier one was fine")
    check(t2_plan.start_reading(STARTUP + edited(BLOCK, OFFLOADED_LINE, b"") + BLOCK, BLOB)[0] is not None, "while a bad earlier block of the same model doesn't")

    with tempfile.TemporaryDirectory() as folder:
        log = pathlib.Path(folder) / "server.log"
        reading = lambda server: faked(server, lambda: t2_plan.server_facts(FakeServer.BASE, t2_plan.MODEL, log))
        absent = reading(FakeServer(log))
        check(absent["real"] and "missing or empty" in absent["load_problem"] and absent["gpu_layers"] is None, "a real server with no log refuses")
        log.write_bytes(STARTUP)
        server = FakeServer(log)
        before = reading(server)
        check("belongs to this model" in before["load_problem"] and not before["loaded"], "a real server whose log holds no load refuses, and /api/ps shows the model isn't loaded")
        server(FakeServer.BASE + "/v1/chat/completions", {})
        after = reading(server)
        check(after["load_problem"] is None and after["loaded"] and after["load_offset"] == START and after["gpu_layers"] == "14/66"
              and after["size_vram"] == 5016660212 and after["log_first_line"] == DATA.split(b"\n")[0], "after a chat the same server gives the facts and the offset")
        plain = lambda url, body=None, timeout=30: {"models": []} if url.endswith(("/api/tags", "/api/ps")) else {}
        fake = faked(plain, lambda: t2_plan.server_facts(FakeServer.BASE, t2_plan.MODEL, folder + "/none.log"))
        check(not fake["real"] and fake["load_problem"] is None and all(fake[f] is None for f in t2_plan.LOAD_FACTS), "a test's fake server skips the log guards")

    def failing(url, body=None, timeout=30):
        raise urllib.error.URLError("down")

    blob = lambda server: faked(server, lambda: t2_plan.model_blob(FakeServer.BASE))
    check(blob(failing) is None, "a server that won't answer /api/show gives no blob, and no error")
    check(blob(lambda url, body=None, timeout=30: {"modelfile": "FROM llama3\n"}) is None, "nor does a modelfile whose FROM names no blob")
    check(blob(FakeServer(FIXTURE)) == BLOB, "the blob comes from the first FROM line")


def check_every_load():
    facts = t2_plan.start_reading(DATA, BLOB)[0]
    first = DATA.split(b"\n")[0]
    scan = lambda data, blob=BLOB, offset=START, line=first: t2_plan.scan_blocks(data, blob, facts, offset, line)
    other = edited_start(BLOCK, BLOB.encode(), b"0" * 64)
    check(scan(DATA) == ([], 1), "the load the run started on matches")
    check(scan(DATA + other) == ([], 1), "another model's load after it is skipped")
    check(scan(DATA + BLOCK) == ([], 2), "and a reload with the same facts matches")
    unloaded = DATA + b'[GIN] 2026/11/11 - 16:30:00 | 200 | 1ms | 127.0.0.1 | POST "/api/generate"\n'
    check(scan(unloaded) == ([], 1), "a model unloaded since, with no new block, isn't a stop")
    split = scan(DATA + edited(BLOCK, OFFLOADED_LINE, b"load_tensors: offloaded 13/66 layers to GPU\n"))
    check(problem_with(split[0], "differs in") and "gpu_layers" in split[0][0] and "load_config" in split[0][0], f"a reload with another split is a stop: {split[0]}")
    # In the log the command's backslashes are doubled.
    projector = scan(DATA + edited_start(BLOCK, b" --mmproj C:\\\\fake\\\\models\\\\blobs\\\\sha256-" + PROJECTOR.encode(), b""))
    check(problem_with(projector[0], "runner_flags"), f"and so is a reload without the projector: {projector[0]}")
    unnamed = scan(DATA + edited_start(BLOCK, b" --model ", b" --mdl "))
    check(problem_with(unnamed[0], "no --model"), "a block with no --model that names a blob stops the run")
    check(problem_with(scan(DATA + edited(BLOCK, OFFLOADED_LINE, b""))[0], "0 offloaded"), "so does a reload of the model with no offloaded line")
    check(problem_with(scan(DATA[:START - 1])[0], "rotated"), "a log shorter than the offset was rotated")
    check(problem_with(scan(b"time=other\n" + DATA.split(b"\n", 1)[1])[0], "rotated"), "a log with another first line was rotated")
    check(problem_with(scan(DATA.replace(b"starting llama-server", b"starting runner", 1))[0], "isn't in the server's log"), "a log with no block where the run's began was replaced")
    check(problem_with(scan(None)[0], "can't be read") and problem_with(scan(DATA, None)[0], "blob"), "no log, and no blob, each stop the run")
    check(scan(DATA.replace(b"\n", b"\r\n"), offset=START + DATA[:START].count(b"\n"), line=first)[1] == 1,
          "a CRLF log is scanned by the same lines, and its offsets are bytes")


def check_load_config_end():
    """The configuration ends at the first `slot` line, where the model starts serving: a configuration-looking line logged
    while it serves isn't part of what the load fixed."""
    slot = b"slot   load_model: id  0 | task -1 | new slot, n_ctx = 32768\n"
    devices = t2_plan.read_blocks(DATA)[1]

    def config(block):
        facts, why = t2_plan.block_facts([text for _, text in t2_plan.split_log(block)], devices)
        return facts["load_config"] if facts else why

    base = config(BLOCK)
    late = edited(BLOCK, slot, slot + b"llama_kv_cache: logged while serving\nwarmup: logged while serving\n")
    check(isinstance(base, list) and len(base) == 185 and config(late) == base,
          "a configuration line logged after the slot line doesn't change the load's configuration")
    unended = late.replace(b"slot ", b"slt ")
    check(isinstance(config(unended), list) and len(config(unended)) == 187,
          "and a block with no slot line is read whole, as before")
    reload = t2_plan.scan_blocks(DATA + late, BLOB, t2_plan.start_reading(DATA, BLOB)[0], START, DATA.split(b"\n")[0])
    check(reload == ([], 2), "so a reload that logs such a line while serving still matches the every-load scan")


